import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const context = { exports: {}, Intl };
vm.runInNewContext(ts.transpileModule(fs.readFileSync("src/lib/firebase-models.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context);
const model = context.exports;
const rows = [{ id: "a", amountCents: 1050, currency: "USD", type: "income" }, { id: "b", amountCents: 200, currency: "USD", type: "expense" }, { id: "c", amountCents: 10000, currency: "NIO", type: "income" }, { id: "d", amountCents: 999, type: "income" }];
assert.equal(model.currencyTotals(rows).USD.income, 1050);
assert.equal(model.currencyTotals(rows).USD.expense, 200);
assert.equal(model.currencyTotals(rows).NIO.income, 10000);
assert.equal(Object.keys(model.currencyTotals(rows)).length, 2, "Never assume the currency of legacy records");
assert.ok(model.formatMoney(1050, "USD").includes("10.50"), "Firestore amounts are integer cents");
assert.ok(!model.formatMoney(1050, "USD").includes("Q"));
assert.equal(model.cents(10.5), null);
assert.equal(model.cents(-1), null);
assert.equal(model.cents("100"), null);
const salary = { id: "s", history: [{ from: "2026-01-01", type: "weekly", currency: "USD", amountCents: 12345 }, { from: "2027-01-01", type: "weekly", currency: "USD", amountCents: 15000 }] };
assert.equal(model.currentSalary(salary, "2026-10-27").amountCents, 12345);
assert.equal(model.currentSalary(salary, "2026-10-27").type, "weekly", "Never convert weekly pay to daily pay");
assert.equal(model.currentSalary(salary, "2025-01-01"), undefined);
assert.equal(model.fullName({ id: "p", firstName: "Persona", lastName: "Prueba" }), "Persona Prueba");
const transport = fs.readFileSync("src/lib/firebase-client.ts", "utf8");
assert.ok(!/\b(?:setDoc|addDoc|updateDoc|deleteDoc|writeBatch|runTransaction|uploadBytes|deleteObject|updateMetadata)\b/.test(transport), "Operational connection must be read-only");
assert.ok(transport.includes("getDocsFromServer") && transport.includes("getDocFromServer"));
assert.ok(transport.includes("memoryLocalCache()") && transport.includes("browserSessionPersistence"));
assert.ok(!transport.includes("localStorage"));
console.log("Firebase model tests passed: cents, separate currencies, salary effective dates and units, protected server reads and no mutation APIs.");
